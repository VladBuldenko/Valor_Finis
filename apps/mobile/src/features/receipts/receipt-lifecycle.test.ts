// The Receipt flow over the REAL transport (VF-MVP-CORE-005), against a fake server that follows the
// documented contract: upload -> process -> review -> confirm. Receipt confirmation has no idempotency
// key; the backend makes it atomic and serialized, so the client's job is to never resend a write by
// itself and to reconcile an unknown outcome by rereading. What is proved here is the client side. The
// native Expo File / FormData part is NOT proved by Node: that needs the device acceptance stage.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { describe, it } from "node:test";

import { QueryClient } from "@tanstack/react-query";

import { json, makeHarness } from "../../api/api-test-support.ts";
import { readApiFailure } from "../../api/api-error-message.ts";
import {
  NETWORK_ERROR_MESSAGE,
  SERVER_ERROR_MESSAGE,
  getUserFacingErrorMessage,
} from "../../api/user-facing-error.ts";
import { recoverFailedConfirmation } from "./receipt-confirm-recovery.ts";
import type { Receipt } from "./receipt.types.ts";

const lostResponse = async () => {
  throw new TypeError("Network request failed");
};

function receiptBody(overrides: Partial<Receipt> = {}): Receipt {
  return {
    id: "r-1",
    user_id: "user-1",
    expense_id: null,
    file_url: null,
    storage_path: "p",
    status: "processed",
    ocr_text: "LIDL",
    merchant_detected: "LIDL",
    total_amount_detected: "3.68",
    currency_detected: "EUR",
    purchase_date_detected: "2026-11-11",
    created_at: "2026-11-11T10:00:00Z",
    updated_at: "2026-11-11T10:00:00Z",
    ...overrides,
  };
}

describe("receipt writes are never resent by the transport", () => {
  for (const [label, path] of [
    ["upload", "/api/v1/receipts/upload"],
    ["process", "/api/v1/receipts/r-1/process"],
    ["confirm", "/api/v1/receipts/r-1/confirm"],
  ] as const) {
    it(`${label} is sent exactly once when the response is lost`, async () => {
      const { transport, calls } = makeHarness({ respond: lostResponse });

      await assert.rejects(() => transport.request(path, { method: "POST", body: "{}" }));
      assert.equal(calls.length, 1);
    });
  }
});

describe("multipart upload", () => {
  it("sends the file as the `file` field with the bearer token and no hand-written Content-Type", async () => {
    const { transport, calls } = makeHarness({ respond: async () => json(201, receiptBody({ status: "uploaded" })) });
    const formData = new FormData();

    formData.append("file", new Blob([new Uint8Array([0x89, 0x50, 0x4e, 0x47])], { type: "image/png" }), "receipt.png");
    await transport.request("/api/v1/receipts/upload", { method: "POST", body: formData });

    assert.equal(calls.length, 1);
    assert.equal(calls[0].headers.get("Authorization"), "Bearer token-1");
    assert.equal(calls[0].headers.has("Content-Type"), false, "the runtime adds the multipart boundary itself");
    assert.ok(calls[0].init.body instanceof FormData);
    assert.equal((calls[0].init.body as FormData).get("file") instanceof Blob, true);
  });

  it("the service builds the part from an Expo File (static source check; the native runtime is a device-stage proof)", () => {
    const source = readFileSync(new URL("./receipt.service.ts", import.meta.url), "utf8");

    assert.match(source, /new File\(image\.uri\)/);
    assert.match(source, /formData\.append\("file", file, file\.name\)/);
    assert.doesNotMatch(source, /append\("file",\s*\{/, "RN 0.86 rejects a plain { uri, name, type } part");
    assert.doesNotMatch(source, /Content-Type/i, "the boundary header is generated by the runtime");
  });
});

describe("an unknown confirmation outcome is reconciled by rereading, never by resending", () => {
  it("a lost confirm response, then a reread: the receipt is confirmed, one Expense exists, a blind retry is a 409", async () => {
    let committed: { expenseId: string } | null = null;
    const { transport, calls } = makeHarness({
      respond: async (call, attempt) => {
        if (call.url.endsWith("/confirm")) {
          if (committed) {
            return json(409, { detail: "Receipt has already been confirmed.", code: "receipt_already_confirmed" });
          }

          committed = { expenseId: "e-1" };

          throw new TypeError("Network request failed"); // committed on the server, answer lost
        }

        return json(200, receiptBody(committed ? { status: "confirmed", expense_id: committed.expenseId } : {}));
      },
    });
    const client = new QueryClient();
    const confirm = () => transport.request("/api/v1/receipts/r-1/confirm", { method: "POST", body: "{}" });
    const reread = (id: string) => transport.request<Receipt>(`/api/v1/receipts/${id}`);

    await assert.rejects(confirm);
    assert.equal(calls.filter((call) => call.url.endsWith("/confirm")).length, 1, "no automatic resend");

    const recovery = await recoverFailedConfirmation(client, "user-1", "r-1", reread);

    assert.deepEqual(recovery, { confirmed: true, expenseId: "e-1" });

    await assert.rejects(confirm, (error: unknown) => readApiFailure(error).status === 409);
    assert.equal(calls.filter((call) => call.url.endsWith("/confirm")).length, 2, "one user-driven retry, refused");
  });

  it("a refused confirmation (nothing written) rereads as processed and leaves the form for another attempt", async () => {
    const { transport } = makeHarness({
      respond: async (call) =>
        call.url.endsWith("/confirm")
          ? json(422, { detail: "Expense currency must match the account's currency to link them.", code: "expense_account_currency_mismatch" })
          : json(200, receiptBody()),
    });
    const client = new QueryClient();

    await assert.rejects(() => transport.request("/api/v1/receipts/r-1/confirm", { method: "POST", body: "{}" }));

    const recovery = await recoverFailedConfirmation(client, "user-1", "r-1", (id) =>
      transport.request<Receipt>(`/api/v1/receipts/${id}`),
    );

    assert.equal(recovery.confirmed, false);
  });
});

describe("a failed OCR attempt keeps the receipt so the user can retry it", () => {
  it("422 on the first process, 200 on the user's retry: the same receipt id, two POSTs, no upload in between", async () => {
    const { transport, calls } = makeHarness({
      respond: async (_call, attempt) =>
        attempt === 1
          ? json(422, { detail: "Receipt OCR processing failed.", code: "receipt_ocr_processing_failed" })
          : json(200, receiptBody()),
    });

    await assert.rejects(() => transport.request("/api/v1/receipts/r-1/process", { method: "POST" }));
    const retried = await transport.request<Receipt>("/api/v1/receipts/r-1/process", { method: "POST" });

    assert.equal(retried.status, "processed");
    assert.deepEqual(calls.map((call) => call.url.split("/api/v1")[1]), ["/receipts/r-1/process", "/receipts/r-1/process"]);
  });
});

describe("what the user reads for each documented refusal", () => {
  const refusals: [number, string][] = [
    [415, "Receipt file type is not supported."],
    [413, "Receipt file is too large."],
    [422, "Receipt file is empty."],
    [422, "Receipt OCR processing failed."],
    [409, "Receipt cannot be processed in its current status."],
    [409, "Receipt has already been confirmed."],
    [409, "Receipt cannot be confirmed in its current status."],
    [422, "Required receipt confirmation data is missing."],
    [404, "Receipt not found."],
    [404, "Receipt file not found."],
  ];

  for (const [status, detail] of refusals) {
    it(`${status} "${detail}" is shown as that sentence`, async () => {
      const { transport } = makeHarness({ respond: async () => json(status, { detail, code: "x" }) });
      const error = await transport.request("/api/v1/receipts/r-1/confirm", { method: "POST", body: "{}" }).catch((e: unknown) => e);

      assert.equal(getUserFacingErrorMessage(error, "fallback"), detail);
    });
  }

  it("a storage failure (500) never shows its body, only the neutral message", async () => {
    const { transport } = makeHarness({
      respond: async () => json(500, { detail: "Receipt file could not be stored.", trace: "psycopg2 at /srv/app.py:12" }),
    });
    const error = await transport.request("/api/v1/receipts/upload", { method: "POST", body: "{}" }).catch((e: unknown) => e);

    assert.equal(getUserFacingErrorMessage(error, "fallback"), SERVER_ERROR_MESSAGE);
  });

  it("a network failure shows the connection message, not the runtime's text", async () => {
    const { transport } = makeHarness({ respond: lostResponse });
    const error = await transport.request("/api/v1/receipts/r-1/process", { method: "POST" }).catch((e: unknown) => e);

    assert.equal(getUserFacingErrorMessage(error, "fallback"), NETWORK_ERROR_MESSAGE);
  });
});
